let cache: BaiGiangSau[] | null = null;

export function baiGiangSau(): BaiGiangSau[] {
  if (cache) return cache;
  const ra: BaiGiangSau[] = [];
  let stt = 0;

  for (const cd of CHU_DE) {
    const tru = TRU.find((t) => t.id === cd.tru)!;
    for (const lv of LEVELS) {
      const tang = Number(lv.tierId.split('-')[1]);
      const ds = DO_SAU[tang - 1];
      stt += 1;
      ra.push({
        id: `bg-${cd.id}-${lv.id}`,
        no: stt,
        truId: cd.tru,
        truTen: tru.ten,
        chuDeId: cd.id,
        ten: `${cd.ten} — mức ${ds.ten}`,
        levelId: lv.id,
        tier: tang,
        cauHoiLoi: cd.cauHoiLoi,
        loi: cd.loi,
        viDu: cd.viDu,
        hocLieu: ds.hocLieu,
        phut: ds.phut,
        viecSauBai: `${cd.viec} Ở mức ${ds.ten}: ${ds.mo.toLowerCase()}`,
        tuKiem: cd.tuKiem,
        bay: cd.bay,
        tuyen: cd.tuyen,
        uuTien: cd.uuTien,
        drillId: cd.drillId,
        phieuDangId: `d-${cd.phieuDangId.slice(2)}`,
      });
    }
  }
  cache = ra;
  return ra;
}

/**
 * Thứ tự học cho một tuyến.
 *
 * Người nhắm IELTS đi theo cấp độ từ thấp lên cao — họ có ba năm và không có
 * ngày thi cố định. Người nhắm chuyên đi theo ƯU TIÊN trong phạm vi cấp của
 * mình: làm hết bài ưu tiên 2 rồi mới tới ưu tiên 1, vì họ chỉ có hai mươi
 * hai tháng và một ngày thi duy nhất.
 */
export function thuTuHoc(tuyen: 'ielts' | 'chuyen', levelId?: string): BaiGiangSau[] {
  const ds = baiGiangSau().filter(
    (b) => b.tuyen.includes(tuyen) && (!levelId || b.levelId === levelId),
  );
  if (tuyen === 'ielts') return ds.sort((a, b) => a.tier - b.tier || a.no - b.no);
  return ds.sort((a, b) => b.uuTien - a.uuTien || a.tier - b.tier || a.no - b.no);
}

