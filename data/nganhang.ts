export const cauCuaChuyenDe = (chuyenDeId: string): CauHoi[] =>
  NGAN_HANG.filter((c) => c.chuyenDeId === chuyenDeId).sort((a, b) => a.no - b.no);

export const cauCuaPhieu = (chuyenDeId: string, loaiMa: string): CauHoi[] =>
  cauCuaChuyenDe(chuyenDeId).filter((c) => c.loaiMa === loaiMa);

/** Chấm một lượt làm. Hàm thuần. */
export function chamCau(ds: CauHoi[], chon: number[]): {
  dung: number;
  tong: number;
  tiLe: number;
  sai: {cau: CauHoi; daChon: number}[];
} {
  const sai: {cau: CauHoi; daChon: number}[] = [];
  let dung = 0;
  ds.forEach((c, i) => {
    if (chon[i] === c.dapAn) dung++;
    else if (chon[i] !== undefined && chon[i] >= 0) sai.push({cau: c, daChon: chon[i]});
  });
  return {dung, tong: ds.length, tiLe: ds.length ? Number(((dung / ds.length) * 100).toFixed(1)) : 0, sai};
}

