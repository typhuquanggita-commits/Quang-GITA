/**
 * Ghép bộ giải với dạng bài. Tên và kỹ năng lấy thẳng từ DANG_BAI để không có
 * hai nguồn sự thật — sửa tên dạng bài ở một chỗ thì cả hai nơi đi theo.
 */
export const GIAI_DE: GiaiDe[] = THO.map((t) => {
  const d = DANG_BAI.find((x) => x.id === t.dangId);
  if (!d) throw new Error(`Bộ giải trỏ tới dạng bài không có: ${t.dangId}`);
  return {...t, dangTen: d.ten, skill: d.skill, drillId: d.drillId};
});

export const GIAI_BY_DANG = Object.fromEntries(GIAI_DE.map((g) => [g.dangId, g])) as Record<string, GiaiDe>;

/**
 * Lời giải riêng cho MỘT phần của phiếu.
 *
 * Cùng một dạng bài, năm phần kiểm cùng điểm kiến thức nhưng khác mức giàn
 * giáo. Vì vậy phần hướng dẫn theo phần được sinh từ vai trò của phần đó,
 * không viết tay bốn trăm lần — bốn trăm bản viết tay sẽ na ná nhau.
 */
export function giaiTheoPhan(dangId: string, phan: PhanPhieu): {
  ma: string;
  ten: string;
  vaiTro: string;
  huong: string;
  neuSaiOPhanNay: string;
} {
  const g = GIAI_BY_DANG[dangId];
  if (!g) throw new Error(`Không có bộ giải cho dạng ${dangId}`);
  const k = KHUNG.find((x) => x.ma === phan.ma)!;
  const huong: Record<PhanPhieu['ma'], string> = {
    KHOI: `Phần này chưa kiểm gì mới. Sai ở đây nghĩa là kiến thức cũ chưa vững — quay lại bài giảng trước khi làm tiếp.`,
    MAU: `Có mẫu trước mặt. Sai ở đây nghĩa là chưa đọc kỹ mẫu, không phải chưa biết. Đọc lại mẫu và làm lại ngay.`,
    DAN: `Còn giàn giáo. Sai ở đây nghĩa là phụ thuộc mẫu nhiều hơn mình tưởng — làm lại phần MẪU thêm một lượt.`,
    TU: `Bỏ giàn giáo. Đây là phần đo thật. Sai ở đây là chỗ cần tra bộ giải kỹ nhất.`,
    CHUOI: `Nối tất cả thành một sản phẩm. Sai ở đây mà bốn phần trước đều đúng nghĩa là biết từng mảnh nhưng chưa ghép được — luyện riêng phần ghép.`,
  };
  return {
    ma: phan.ma,
    ten: phan.ten,
    vaiTro: k.vaiTro,
    huong: huong[phan.ma],
    neuSaiOPhanNay:
      phan.ma === 'TU' || phan.ma === 'CHUOI'
        ? `${g.neuSai}`
        : `Chưa cần đổi kế hoạch. Làm lại đúng phần này rồi đi tiếp.`,
  };
}

